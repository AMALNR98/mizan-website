function translateTextNode(node) {
  const raw = node.nodeValue;
  const key = raw.replace(/\s+/g, " ").trim();
  if (!key || !arabicDictionary.has(key)) return;
  const start = raw.match(/^\s*/)?.[0] || "";
  const end = raw.match(/\s*$/)?.[0] || "";
  node.nodeValue = `${start}${arabicDictionary.get(key)}${end}`;
}

function translateSubtree(root) {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root);
    return;
  }
  if (root.nodeType !== Node.ELEMENT_NODE && root.nodeType !== Node.DOCUMENT_FRAGMENT_NODE) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode())) {
    const parent = node.parentElement;
    if (!parent || parent.matches("script, style")) continue;
    translateTextNode(node);
  }
}

const savedLanguage = localStorage.getItem("mizan-language") || "en";
const languageToggle = document.querySelector("[data-lang-toggle]");

if (languageToggle) {
  languageToggle.addEventListener("click", () => {
    localStorage.setItem("mizan-language", savedLanguage === "ar" ? "en" : "ar");
    window.location.reload();
  });
}

if (savedLanguage === "ar") {
  document.documentElement.lang = "ar";
  document.documentElement.dir = "rtl";
  document.body.classList.add("is-arabic");
  document.title = arabicTitles.get(document.title) || document.title;
  if (languageToggle) {
    languageToggle.textContent = "English";
    languageToggle.setAttribute("aria-label", "Switch to English");
  }
  translateSubtree(document.body);

  const observer = new MutationObserver((mutations) => {
    for (const mutation of mutations) {
      mutation.addedNodes.forEach(translateSubtree);
    }
  });
  observer.observe(document.body, { childList: true, subtree: true });
}
